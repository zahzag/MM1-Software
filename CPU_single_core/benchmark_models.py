#!/usr/bin/env python3
"""Benchmark multiple ML regressors on repository datasets."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingRegressor, RandomForestRegressor
from sklearn.linear_model import LinearRegression, Ridge
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsRegressor
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parents[1]
DATASET_DIR = ROOT / "Dataset"
OUTPUT_DIR = ROOT / "CPU_single_core"
RESULTS_JSON = OUTPUT_DIR / "benchmark_results.json"
REPORT_MD = OUTPUT_DIR / "Ml.md"

DATASETS = {
    "x86": DATASET_DIR / "x86_mm1_cleaned.csv",
    "arm": DATASET_DIR / "arm_mm1_cleaned.csv",
}

TARGETS = [
    "Measured MRT [ms]",
    "Measured Mean CORE Frequency [KHz]",
    "Modeled CORE Power [W]",
]

RANDOM_STATE = 42
TEST_SIZE = 0.2
BEST_MODEL_METRIC = "r2"
KNN_NEIGHBORS = 7
RF_ESTIMATORS = 400


def _build_models() -> Dict[str, Pipeline]:
    return {
        "LinearRegression": Pipeline([
            ("scaler", StandardScaler()),
            ("model", LinearRegression()),
        ]),
        "Ridge": Pipeline([
            ("scaler", StandardScaler()),
            ("model", Ridge(alpha=1.0, random_state=RANDOM_STATE)),
        ]),
        "KNN": Pipeline([
            ("scaler", StandardScaler()),
            ("model", KNeighborsRegressor(n_neighbors=KNN_NEIGHBORS)),
        ]),
        "RandomForest": Pipeline([
            (
                "model",
                RandomForestRegressor(
                    n_estimators=RF_ESTIMATORS,
                    random_state=RANDOM_STATE,
                    n_jobs=-1,
                ),
            )
        ]),
        "GradientBoosting": Pipeline([
            ("model", GradientBoostingRegressor(random_state=RANDOM_STATE))
        ]),
    }


def _prepare_xy(df: pd.DataFrame, target: str) -> Tuple[pd.DataFrame, pd.Series]:
    numeric_df = df.apply(pd.to_numeric, errors="coerce")
    feature_df = numeric_df.drop(columns=[target], errors="ignore")
    feature_df = feature_df.dropna(axis=1, how="all")
    target_series = numeric_df[target]
    clean_df = feature_df.join(target_series.rename(target)).dropna()
    x = clean_df.drop(columns=[target])
    y = clean_df[target]
    return x, y


def _metrics(y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, float]:
    mse = mean_squared_error(y_true, y_pred)
    return {
        "mae": float(mean_absolute_error(y_true, y_pred)),
        "rmse": float(np.sqrt(mse)),
        "r2": float(r2_score(y_true, y_pred)),
    }


def benchmark_dataset(df: pd.DataFrame) -> Dict[str, Any]:
    results: Dict[str, Any] = {"targets": {}}

    for target in TARGETS:
        if target not in df.columns:
            continue

        x, y = _prepare_xy(df, target)
        if x.empty:
            continue

        x_train, x_test, y_train, y_test = train_test_split(
            x, y, test_size=TEST_SIZE, random_state=RANDOM_STATE
        )

        model_scores: Dict[str, Dict[str, float]] = {}

        for model_name, model in _build_models().items():
            model.fit(x_train, y_train)
            pred = model.predict(x_test)
            model_scores[model_name] = _metrics(y_test.values, pred)

        best_model = max(
            model_scores.items(),
            key=lambda model_item: model_item[1][BEST_MODEL_METRIC],
        )

        results["targets"][target] = {
            "rows_used": int(len(x)),
            "train_rows": int(len(x_train)),
            "test_rows": int(len(x_test)),
            "best_model": best_model[0],
            "best_model_metrics": best_model[1],
            "all_models": model_scores,
        }

    return results


def _fmt(v: float) -> str:
    return f"{v:.4f}"


def write_markdown(results: Dict[str, Any]) -> None:
    lines: List[str] = []
    lines.append("# ML Benchmark (CPU Single Core Dataset)")
    lines.append("")
    lines.append("This report is generated by `CPU_single_core/benchmark_models.py`.")
    lines.append("")
    lines.append("## How to run")
    lines.append("")
    lines.append("```bash")
    lines.append("python CPU_single_core/benchmark_models.py")
    lines.append("```")
    lines.append("")
    lines.append(f"Best model selection metric: `{BEST_MODEL_METRIC.upper()}`.")
    lines.append("")

    for dataset_name, dataset_result in results.items():
        lines.append(f"## Dataset: {dataset_name}")
        lines.append("")

        targets = dataset_result.get("targets", {})
        for target_name, target_result in targets.items():
            lines.append(f"### Target: {target_name}")
            lines.append("")
            lines.append(
                f"Rows used: {target_result['rows_used']} (train={target_result['train_rows']}, test={target_result['test_rows']})"
            )
            lines.append("")
            lines.append("| Model | MAE | RMSE | R² |")
            lines.append("|---|---:|---:|---:|")

            sorted_models = sorted(
                target_result["all_models"].items(),
                key=lambda item: item[1]["r2"],
                reverse=True,
            )
            for model_name, metrics in sorted_models:
                lines.append(
                    f"| {model_name} | {_fmt(metrics['mae'])} | {_fmt(metrics['rmse'])} | {_fmt(metrics['r2'])} |"
                )

            lines.append("")
            best = target_result["best_model"]
            lines.append(f"Best model: **{best}**")
            lines.append("")

    REPORT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    all_results: Dict[str, Any] = {}

    for dataset_name, dataset_path in DATASETS.items():
        df = pd.read_csv(dataset_path)
        all_results[dataset_name] = benchmark_dataset(df)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps(all_results, indent=2), encoding="utf-8")
    write_markdown(all_results)

    print(f"Saved benchmark JSON: {RESULTS_JSON}")
    print(f"Saved benchmark report: {REPORT_MD}")


if __name__ == "__main__":
    main()
